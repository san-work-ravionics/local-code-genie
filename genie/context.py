"""Build the per-task context packet: conventions, reusable code, relevant docs.

The packet is written to ``context.md`` in the run folder and passed to Aider
with ``--read``. It is the same file that goes to the remote model, so the UI
can show exactly what left the machine.
"""

from __future__ import annotations

from pathlib import Path

from .config import Target

LANG = {".py": "python", ".js": "javascript", ".jsx": "jsx", ".css": "css", ".html": "html",
        ".ts": "typescript", ".md": "markdown"}


def _snippet(root: Path, item: dict, max_lines: int = 30) -> str:
    p = root / item["file"]
    try:
        lines = p.read_text(encoding="utf-8-sig", errors="replace").splitlines()
    except OSError:
        return ""
    start = max(1, item["line"] - len(item.get("decorators", [])))
    end = min(item.get("end", start), start + max_lines - 1)
    body = "\n".join(lines[start - 1:end])
    more = "\n    # ... (truncated)" if item.get("end", end) > end else ""
    return body + more


def _is_test(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return "/tests/" in f"/{path}" or name.startswith("test_") or name.endswith((".test.js", "_test.py"))


def choose_files(code_matches: list[dict], limit: int, task: str = "") -> list[str]:
    """Pick files to edit: source files first; test files only if the task is about tests."""
    wants_tests = "test" in task.lower()
    ordered = [m for m in code_matches if wants_tests or not _is_test(m["file"])]
    out: list[str] = []
    for m in ordered:
        if m["kind"] in {"css-var"}:
            continue
        if m["file"] not in out:
            out.append(m["file"])
        if len(out) >= limit:
            break
    return out


def build_context(target: Target, settings: dict, task: str, code: list[dict],
                  docs: list[dict], editable: list[str],
                  class_api: dict[str, list[str]] | None = None) -> str:
    cfg = settings["context"]
    max_chars = cfg["max_chars"]
    parts: list[str] = ["# Genie context (read-only; do not edit this file)\n"]

    conv = target.conventions_path
    if conv.exists():
        parts.append("## Project conventions: follow these strictly\n")
        parts.append(conv.read_text(encoding="utf-8").strip() + "\n")

    if class_api:
        parts.append("\n## Classes used in the file you are editing: these are ALL the methods they have\n")
        parts.append("Call only these (or add a new method to the class in this change).\n")
        for cls, sigs in class_api.items():
            parts.append(f"- `{cls}`:\n")
            parts.extend(f"    - `{s}`\n" for s in sigs[:20])

    wants_tests = "test" in task.lower()
    code = [m for m in code if wants_tests or not _is_test(m["file"])]
    if code:
        parts.append("\n## Possibly related existing code (for reference: reuse only what fits the task; "
                     "do not re-implement it)\n")
        for m in code[:10]:
            if m["file"] in editable and m["kind"] == "module":
                continue
            doc = f": {m['doc']}" if m.get("doc") else ""
            parts.append(f"- `{m['sig']}` in `{m['file']}:{m['line']}`{doc}\n")
        shown = 0
        for m in code:
            if shown >= cfg["snippets"]:
                break
            if m["kind"] in {"module", "css-var", "html-id"} or m["file"] in editable:
                continue
            snip = _snippet(target.root, m)
            if not snip.strip():
                continue
            lang = LANG.get(Path(m["file"]).suffix.lower(), "")
            parts.append(f"\n### {m['file']}:{m['line']}\n```{lang}\n{snip}\n```\n")
            shown += 1

    tokens = [m for m in code if m["kind"] == "css-var"]
    if tokens:
        parts.append("\n## Design tokens already defined (use these instead of new colours or sizes)\n")
        parts.extend(f"- `{m['sig']}` ({m['file']})\n" for m in tokens[:12])

    if docs:
        parts.append("\n## Relevant project docs\n")
        for d in docs[: cfg["doc_sections"]]:
            snip = _snippet(target.root, d, max_lines=40)
            parts.append(f"\n### {d['sig']}\n{snip}\n")

    rules = target.cfg.get("rules", [])
    if rules:
        parts.append("\n## Rules genie checks after your edit (violations are rejected)\n")
        parts.extend(f"- {r.get('description', r['id'])}\n" for r in rules)
    parts.append("- Do not delete or rename existing functions, classes or CSS rules unless asked.\n")
    parts.append("- Only edit the files you were asked to edit.\n")

    text = "".join(parts)
    if len(text) > max_chars:
        text = text[:max_chars] + "\n\n(context truncated to fit the local model)\n"
    return text


INSERT_GUIDE = (
    "- How to ADD code with SEARCH/REPLACE: SEARCH for 2-4 existing lines next to where the new code "
    "belongs (for example the `@router...` line and `def` line of an existing function). In REPLACE, "
    "write your new code, then repeat those SEARCH lines unchanged (or the other way round). "
    "Every line in SEARCH must also appear in REPLACE; never use REPLACE to drop existing code.")


def task_message(task: str, editable: list[str], feedback: str | None = None,
                 escalated_from_local: bool = False, edit_format: str = "diff") -> str:
    msg = [task.strip(), "",
           "Constraints:",
           f"- Edit only: {', '.join(editable)}." if editable else "- Keep the change minimal.",
           "- Reuse the existing helpers, styles and patterns listed in the genie context file.",
           "- Call only methods that already exist (see the context file), or add them in this change.",
           "- Do not remove or rename existing code the task does not mention.",
           "- Keep the change minimal and consistent with the project conventions."]
    if edit_format == "diff":
        msg.append(INSERT_GUIDE)
    if feedback:
        who = "A previous attempt (by a smaller local model)" if escalated_from_local else "Your previous attempt"
        msg += ["", f"{who} was rejected by automated checks:", feedback,
                "Make a fresh edit that avoids these problems."]
    return "\n".join(msg)


def insert_prompt(context_text: str, rel: str, src: str, task: str, feedback: str | None = None) -> str:
    """Prompt for insert mode: the model sees the file but answers with new code only."""
    lang = LANG.get(Path(rel).suffix.lower(), "")
    parts = [context_text.strip(), "",
             f"## The file you are adding to: `{rel}` (for reference; do not repeat it)",
             f"```{lang}\n{src.rstrip()}\n```", "",
             "## Task", task.strip(), ""]
    if feedback:
        parts += ["## Your previous answer was rejected by automated checks", feedback, "",
                  "Write a corrected version of the NEW code only.", ""]
    parts.append("Reply with only the new code in one ```python block.")
    return "\n".join(parts)


def estimate_tokens(text: str) -> int:
    return len(text) // 4 + 1
